"""Generate narrow sudoers rules for the commands Polarum actually runs.

The rules are built from the same argument lists the runner and actions execute
(`runner.start_argv`, `runner.JOURNAL_ARGV`, `runner.snapshot_argv`,
`actions.POWER_COMMANDS`), so they cannot drift from the code. Variable parts
(the 12-character run token and the snapshot timestamp) use fixed-length `?`
wildcards, which cannot match extra arguments. Nothing here runs sudo.
"""
from __future__ import annotations

import re

from .actions import POWER_COMMANDS
from .runner import JOURNAL_ARGV, UNIT_NAME, snapshot_argv, start_argv

BIN = {
    "systemctl": "/usr/bin/systemctl", "apt-get": "/usr/bin/apt-get",
    "systemd-run": "/usr/bin/systemd-run", "journalctl": "/usr/bin/journalctl",
    "pvecm": "/usr/bin/pvecm", "qm": "/usr/sbin/qm", "pct": "/usr/sbin/pct",
    "zfs": "/usr/sbin/zfs",
}
TOKEN_LENGTH = 12
SNAPSHOT_STAMP = "????????-??????"          # YYYYMMDD-HHMMSS
DEFAULT_DATASET = "rpool/ROOT/pve-1"
_SPECIAL = set(",:=\\*?[]")


class Wild(str):
    """An argument (or tail) that is already a sudoers pattern: not escaped."""


def escape(arg: str) -> str:
    """Escape one literal argument for a sudoers command specification."""
    return "".join(f"\\{ch}" if ch in _SPECIAL or ch.isspace() else ch for ch in arg)


def render(argv: list[str | Wild]) -> str:
    """Render [command, args...]; a Wild is emitted verbatim, other strings escaped."""
    out = [BIN.get(argv[0], argv[0])]
    out += [a if isinstance(a, Wild) else escape(a) for a in argv[1:]]
    return " ".join(out)


def token_pattern() -> Wild:
    return Wild("?" * TOKEN_LENGTH)


def apply_rules(dataset: str = DEFAULT_DATASET) -> list[str]:
    start = start_argv("x" * TOKEN_LENGTH)
    start[-1] = token_pattern()
    snapshot = snapshot_argv(dataset, "polarum-pre-upgrade-")
    snapshot[-1] = Wild(escape(snapshot[-1]) + SNAPSHOT_STAMP)
    return [render(start), render(list(JOURNAL_ARGV)), render(snapshot)]


def power_rules() -> list[str]:
    return [render(cmd[2:]) for cmd in POWER_COMMANDS.values()]


def preflight_rules() -> list[str]:
    return [render(["qm", "list"]), render(["pct", "list"]), render(["pvecm", "status"])]


def check_rules() -> list[str]:
    return [render(["apt-get", "update"])]


def generate(user: str = "polarum", dataset: str = DEFAULT_DATASET) -> str:
    """The complete /etc/sudoers.d/polarum content (apply rule commented out)."""
    def alias(name: str, rules: list[str]) -> str:
        return f"Cmnd_Alias {name} = " + ", \\\n    ".join(rules)

    return "\n".join([
        "# Generated by `polarum --print-sudoers`. Install with: visudo -f /etc/sudoers.d/polarum",
        "# Verify the binary paths first: command -v systemctl qm pct pvecm apt-get "
        "systemd-run journalctl zfs",
        "",
        "# Power off / reboot",
        alias("POLARUM_POWER", power_rules()),
        "",
        "# Read-only pre-flight (Proxmox nodes only)",
        alias("POLARUM_PREFLIGHT", preflight_rules()),
        "",
        "# Update check (refreshes package lists; installs nothing)",
        alias("POLARUM_CHECK", check_rules()),
        "",
        f"# Update apply. Each rule is one exact command line: the {UNIT_NAME} unit, its",
        "# journal tail, and a ZFS snapshot of ONE dataset. Replace the dataset with your",
        "# root dataset (findmnt -n -o SOURCE /). Add the last line only on nodes where",
        "# Polarum should install updates.",
        alias("POLARUM_APPLY", apply_rules(dataset)),
        "",
        f"{user} ALL=(root) NOPASSWD: POLARUM_POWER, POLARUM_PREFLIGHT, POLARUM_CHECK",
        f"# {user} ALL=(root) NOPASSWD: POLARUM_APPLY",
        "",
    ])


def _unescape_to_regex(pattern: str) -> str:
    out, i = [], 0
    while i < len(pattern):
        ch = pattern[i]
        if ch == "\\" and i + 1 < len(pattern):
            out.append(re.escape(pattern[i + 1]))
            i += 2
            continue
        out.append("." if ch == "?" else re.escape(ch))
        i += 1
    return "".join(out)


def split_rule(rule: str) -> list[str]:
    """Split a rendered rule into its arguments (honouring backslash escapes)."""
    args, cur, i = [], "", 0
    while i < len(rule):
        ch = rule[i]
        if ch == "\\" and i + 1 < len(rule):
            cur += rule[i:i + 2]
            i += 2
        elif ch == " ":
            args.append(cur)
            cur = ""
            i += 1
        else:
            cur += ch
            i += 1
    args.append(cur)
    return args


def matches(rule: str, argv: list[str]) -> bool:
    """Approximate sudo's matching: same command path, same argument count, per-arg pattern."""
    parts = split_rule(rule)
    if len(parts) != len(argv):
        return False
    if parts[0] != BIN.get(argv[0], argv[0]):
        return False
    return all(re.fullmatch(_unescape_to_regex(p), a, re.S) is not None
               for p, a in zip(parts[1:], argv[1:], strict=True))

